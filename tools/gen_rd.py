#!/usr/bin/env python3
"""Generate src/rd/table.rs: the R_d step constants.

ALPHA[D - 1][j - 1] = floor(phi_D^-j * 2^64) | 1 for D = 1..=MAX_DIM, j = 1..=D, where
phi_D is the positive root of x^(D+1) = x + 1. The 32-bit constants are derived in Rust
as (ALPHA >> 32) | 1, which equals floor(phi_D^-j * 2^32) | 1.

Uses only the standard library (80-digit decimal arithmetic).

    python3 tools/gen_rd.py            # rewrite src/rd/table.rs
    python3 tools/gen_rd.py --check    # fail if the file is out of date
"""

import argparse
import decimal
import pathlib
import sys
from decimal import Decimal

decimal.getcontext().prec = 80
MAX_DIM = 16
OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "rd" / "table.rs"

# Section 5.2 of docs/spec.md, checked independently with mpmath.
SPEC = {
    (1, 1): 0x9E3779B97F4A7C15,
    (2, 1): 0xC13FA9A902A6328F,
    (2, 2): 0x91E10DA5C79E7B1D,
    (3, 1): 0xD1B54A32D192ED03,
    (3, 2): 0xABC98388FB8FAC03,
    (3, 3): 0x8CB92BA72F3D8DD7,
}


def phi(d: int) -> Decimal:
    """Positive root of x^(d+1) = x + 1, by Newton's method from 2."""
    x = Decimal(2)
    for _ in range(1000):
        nx = x - (x ** (d + 1) - x - 1) / ((d + 1) * x**d - 1)
        if nx == x:
            return x
        x = nx
    raise RuntimeError(f"Newton did not converge for d = {d}")


def alphas(d: int) -> list[int]:
    p = phi(d)
    scale = Decimal(2) ** 64
    return [int((scale / p**j).to_integral_value(rounding=decimal.ROUND_FLOOR)) | 1 for j in range(1, d + 1)]


def render() -> str:
    rows = []
    for d in range(1, MAX_DIM + 1):
        vals = alphas(d) + [0] * (MAX_DIM - d)
        rows.append("    [" + ", ".join(f"0x{v:016X}" if v else "0" for v in vals) + "],")
    return (
        "// @generated by tools/gen_rd.py. Do not edit by hand.\n"
        "\n"
        "/// Largest dimension R_d supports.\n"
        f"pub(crate) const MAX_DIM: usize = {MAX_DIM};\n"
        "\n"
        "/// `ALPHA[D - 1][j - 1]` is `floor(phi_D^-j * 2^64) | 1`, where `phi_D` is the positive\n"
        "/// root of `x^(D+1) = x + 1`. Entries with `j > D` are zero.\n"
        "#[rustfmt::skip]\n"
        "pub(crate) const ALPHA: [[u64; MAX_DIM]; MAX_DIM] = [\n" + "\n".join(rows) + "\n];\n"
    )


def self_test() -> None:
    for (d, j), want in SPEC.items():
        got = alphas(d)[j - 1]
        assert got == want, f"D={d} j={j}: {got:#x} != {want:#x}"
    for d in range(1, MAX_DIM + 1):
        p = phi(d)
        assert abs(p ** (d + 1) - p - 1) < Decimal(10) ** -70
        assert all(a & 1 for a in alphas(d))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if the table is out of date")
    args = ap.parse_args()
    self_test()
    text = render()
    if args.check:
        if OUT.read_text() != text:
            print(f"{OUT} is out of date; run tools/gen_rd.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
