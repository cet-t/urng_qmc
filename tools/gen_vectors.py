#!/usr/bin/env python3
"""Generate tests/data/sobol_vectors.rs: expected Sobol points for the Rust tests.

The 32-bit values come from scipy.stats.qmc.Sobol(scramble=False, bits=32), which are
exact integers after scaling by 2^32. The 64-bit values come from an independent Python
implementation (Gray-code order, like SciPy), whose 32-bit output is first checked
against SciPy.

    python3 tools/gen_vectors.py           # rewrite tests/data/sobol_vectors.rs
    python3 tools/gen_vectors.py --check   # fail if the file is out of date

Requires numpy and scipy.
"""

import argparse
import pathlib
import sys
import warnings

import numpy as np
from scipy.stats import qmc

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import gen_sobol  # noqa: E402

OUT = pathlib.Path(__file__).resolve().parent.parent / "tests" / "data" / "sobol_vectors.rs"
POINTS = 256
SMALL_D = 8
BIG_D = 1024


def direction_numbers(rows, dims: int, bits: int) -> list[list[int]]:
    """v[d][k] for d < dims, k < bits (section 5.4 of docs/spec.md)."""
    v = [[1 << (bits - 1 - k) for k in range(bits)]]
    for _, s, a, m in rows[: dims - 1]:
        vd = []
        for k in range(bits):
            if k < s:
                vd.append(m[k] << (bits - 1 - k))
            else:
                x = vd[k - s] ^ (vd[k - s] >> s)
                for i in range(1, s):
                    if (a >> (s - 1 - i)) & 1:
                        x ^= vd[k - i]
                vd.append(x)
        v.append(vd)
    return v


def reference(rows, dims: int, bits: int, n: int) -> list[list[int]]:
    v = direction_numbers(rows, dims, bits)
    x = [0] * dims
    out = []
    for i in range(n):
        out.append(list(x))
        c = (~i & (i + 1)).bit_length() - 1  # position of the lowest zero bit of i
        x = [x[d] ^ v[d][c] for d in range(dims)]
    return out


def scipy_u32(dims: int, n: int) -> list[list[int]]:
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        pts = qmc.Sobol(dims, scramble=False, bits=32).random(n)
    scaled = pts * 2.0**32
    assert np.all(scaled == np.floor(scaled))
    return scaled.astype(np.uint64).tolist()


def checksum(points, dims: int) -> list[int]:
    h = [0] * dims
    for p in points:
        for d in range(dims):
            h[d] = (((h[d] << 5) | (h[d] >> 27)) & 0xFFFFFFFF) ^ p[d]
    return h


def array(name: str, ty: str, rows, fmt) -> str:
    body = "\n".join("    [" + ", ".join(fmt(x) for x in r) + "]," for r in rows)
    return f"#[rustfmt::skip]\npub const {name}: [[{ty}; {len(rows[0])}]; {len(rows)}] = [\n{body}\n];\n"


def render() -> str:
    rows = gen_sobol.from_scipy()
    gen_sobol.check(rows)

    small32 = scipy_u32(SMALL_D, POINTS)
    assert reference(rows, SMALL_D, 32, POINTS) == small32
    small64 = reference(rows, SMALL_D, 64, POINTS)
    assert [[x >> 32 for x in p] for p in small64] == small32

    big32 = scipy_u32(BIG_D, POINTS)
    assert reference(rows, BIG_D, 32, POINTS) == big32
    sums = checksum(big32, BIG_D)

    return (
        "// @generated by tools/gen_vectors.py. Do not edit by hand.\n"
        "//\n"
        "// 32-bit values: scipy.stats.qmc.Sobol(scramble=False, bits=32), scaled by 2^32.\n"
        "// 64-bit values: Python reference implementation, high halves checked against SciPy.\n"
        "\n"
        f"pub const POINTS: usize = {POINTS};\n"
        "\n"
        + array("SOBOL32_D8", "u32", small32, lambda x: f"0x{x:08X}")
        + "\n"
        + array("SOBOL64_D8", "u64", small64, lambda x: f"0x{x:016X}")
        + "\n"
        "/// Per dimension: `h = h.rotate_left(5) ^ x` over the first `POINTS` points of a\n"
        f"/// {BIG_D}-dimensional Sobol32 sequence.\n"
        + "#[rustfmt::skip]\n"
        + f"pub const SOBOL32_D{BIG_D}_CHECKSUM: [u32; {BIG_D}] = [\n"
        + "\n".join("    " + ", ".join(f"0x{x:08X}" for x in sums[i : i + 8]) + "," for i in range(0, BIG_D, 8))
        + "\n];\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = ap.parse_args()
    text = render()
    if args.check:
        if OUT.read_text() != text:
            print(f"{OUT} is out of date; run tools/gen_vectors.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
