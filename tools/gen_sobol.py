#!/usr/bin/env python3
"""Generate src/sobol/table.rs from the Joe-Kuo direction numbers.

The source is either the original file `new-joe-kuo-6.21201` from
https://web.maths.unsw.edu.au/~fkuo/sobol/ or the same data bundled with SciPy
(`scipy/stats/_sobol_direction_numbers.npz`):

    python3 tools/gen_sobol.py --joe-kuo new-joe-kuo-6.21201
    python3 tools/gen_sobol.py --scipy
    python3 tools/gen_sobol.py --scipy --check     # fail if the file is out of date

Dimension 1 is implicit (all m_k = 1). The table lists dimensions 2..=MAX_DIM as
(s, a, [m_1, ..., m_s, 0, ...]) in Joe-Kuo notation.
"""

import argparse
import pathlib
import sys

OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "sobol" / "table.rs"

# The first rows of new-joe-kuo-6.21201 (d, s, a, m_1..m_s), used to check either source.
KNOWN = [
    (2, 1, 0, [1]),
    (3, 2, 1, [1, 3]),
    (4, 3, 1, [1, 3, 1]),
    (5, 3, 2, [1, 1, 1]),
    (6, 4, 1, [1, 1, 3, 3]),
    (7, 4, 4, [1, 3, 5, 13]),
    (8, 5, 2, [1, 1, 5, 5, 17]),
    (9, 5, 4, [1, 1, 5, 5, 5]),
    (10, 5, 7, [1, 1, 7, 11, 19]),
]


def from_joe_kuo(path: pathlib.Path) -> list[tuple[int, int, int, list[int]]]:
    rows = []
    with path.open() as f:
        next(f)  # header: d s a m_i
        for line in f:
            if not line.strip():
                continue
            d, s, a, *m = map(int, line.split())
            assert len(m) == s, f"dimension {d}: expected {s} m values"
            rows.append((d, s, a, m))
    return rows


def from_scipy() -> list[tuple[int, int, int, list[int]]]:
    import numpy as np
    import scipy

    npz = pathlib.Path(scipy.__file__).parent / "stats" / "_sobol_direction_numbers.npz"
    z = np.load(npz)
    poly, vinit = z["poly"], z["vinit"]
    rows = []
    # Row i of the arrays is dimension i + 1. poly = 1 | a << 1 | 1 << s.
    for i in range(1, len(poly)):
        p = int(poly[i])
        s = p.bit_length() - 1
        a = (p >> 1) & ((1 << (s - 1)) - 1)
        rows.append((i + 1, s, a, [int(v) for v in vinit[i][:s]]))
    return rows


def check(rows) -> None:
    for want in KNOWN:
        got = rows[want[0] - 2]
        assert got == want, f"dimension {want[0]}: {got} != {want}"
    for i, (d, s, a, m) in enumerate(rows):
        assert d == i + 2
        assert 1 <= s and 0 <= a < (1 << max(s - 1, 0))
        for k, mk in enumerate(m, start=1):
            assert mk % 2 == 1 and mk < (1 << k), f"dimension {d}: bad m_{k} = {mk}"


def render(rows, max_dim: int, source: str) -> str:
    rows = rows[: max_dim - 1]
    assert len(rows) == max_dim - 1, f"source has only {len(rows) + 1} dimensions"
    max_degree = max(s for _, s, _, _ in rows)
    body = "\n".join(
        f"    ({s}, {a}, [{', '.join(map(str, m + [0] * (max_degree - s)))}]),"
        for _, s, a, m in rows
    )
    return (
        f"// @generated by tools/gen_sobol.py from {source}. Do not edit by hand.\n"
        "//\n"
        "// Direction numbers from S. Joe and F. Y. Kuo, \"Constructing Sobol sequences with better\n"
        "// two-dimensional projections\", SIAM J. Sci. Comput. 30 (2008). See NOTICE.\n"
        "\n"
        "/// Largest dimension the table covers.\n"
        f"pub(crate) const MAX_DIM: usize = {max_dim};\n"
        "\n"
        "/// Largest polynomial degree `s` in [`PARAMS`].\n"
        f"pub(crate) const MAX_DEGREE: usize = {max_degree};\n"
        "\n"
        "/// `(s, a, [m_1, ..., m_s, 0, ...])` for dimensions `2..=MAX_DIM`.\n"
        "///\n"
        "/// Only read while evaluating the direction-number constants, so it never reaches the\n"
        "/// binary.\n"
        "#[allow(clippy::large_const_arrays)]\n"
        "#[rustfmt::skip]\n"
        "pub(crate) const PARAMS: [(u8, u32, [u32; MAX_DEGREE]); MAX_DIM - 1] = [\n" + body + "\n];\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    src = ap.add_mutually_exclusive_group(required=True)
    src.add_argument("--joe-kuo", type=pathlib.Path, help="path to new-joe-kuo-6.21201")
    src.add_argument("--scipy", action="store_true", help="read the copy bundled with SciPy")
    ap.add_argument("--max-dim", type=int, default=1024)
    ap.add_argument("--check", action="store_true", help="fail if the table is out of date")
    args = ap.parse_args()

    rows = from_scipy() if args.scipy else from_joe_kuo(args.joe_kuo)
    check(rows)
    # Both sources hold the same data, so the header names the original file either way.
    text = render(rows, args.max_dim, "new-joe-kuo-6.21201")
    if args.check:
        if OUT.read_text() != text:
            print(f"{OUT} is out of date; run tools/gen_sobol.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
